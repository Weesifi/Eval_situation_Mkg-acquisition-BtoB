// Gestionnaire des utilisateurs enregistrés avec versionnage pour rafraîchir le cache local
const DB_VERSION_KEY = "acquisition_quest_b2b_users_v3";

function getRegisteredUsers() {
  const localData = localStorage.getItem(DB_VERSION_KEY);
  if (!localData) {
    localStorage.setItem(DB_VERSION_KEY, JSON.stringify(INITIAL_STUDENT_COHORT));
    return [...INITIAL_STUDENT_COHORT];
  }
  try {
    const parsed = JSON.parse(localData);
    if (!Array.isArray(parsed) || parsed.length === 0 || !parsed[0].answers || Object.keys(parsed[0].answers).length < 10) {
      localStorage.setItem(DB_VERSION_KEY, JSON.stringify(INITIAL_STUDENT_COHORT));
      return [...INITIAL_STUDENT_COHORT];
    }
    return parsed;
  } catch (e) {
    return [...INITIAL_STUDENT_COHORT];
  }
}

function saveRegisteredUsers(users) {
  localStorage.setItem(DB_VERSION_KEY, JSON.stringify(users));
}

function getCurrentUserSession() {
  const session = localStorage.getItem("acquisition_quest_b2b_session");
  if (!session) return null;
  try {
    return JSON.parse(session);
  } catch (e) {
    return null;
  }
}

function setCurrentUserSession(user) {
  localStorage.setItem("acquisition_quest_b2b_session", JSON.stringify(user));
}

function clearUserSession() {
  localStorage.removeItem("acquisition_quest_b2b_session");
}
